# Embeds into hk-tycoon.html: simplified SVG outlines of the 18 District Council districts
# from the official 2021 census boundaries (C&SD via CSDI portal: data/raw/dc_21c.geojson).
# Run from the project folder: python tools/build_map.py
import json, math
from shapely.geometry import shape, MultiPolygon

SRC = 'data/raw/dc_21c.geojson'
OUT = 'hk-tycoon.html'
KEYS = {'Central and Western': 'CW', 'Wan Chai': 'WC', 'Eastern': 'EA', 'Southern': 'SO', 'Yau Tsim Mong': 'YT',
        'Sham Shui Po': 'SS', 'Kowloon City': 'KC', 'Wong Tai Sin': 'WT', 'Kwun Tong': 'KT', 'Kwai Tsing': 'KW',
        'Tsuen Wan': 'TW', 'Tuen Mun': 'TM', 'Yuen Long': 'YL', 'North': 'NO', 'Tai Po': 'TP', 'Sha Tin': 'ST',
        'Sai Kung': 'SK', 'Islands': 'IS'}
W = 640                      # SVG width in px
TOL = 0.0012                 # simplification tolerance in degrees (~120 m)
MIN_AREA = 0.6e-5            # drop islets smaller than this (deg^2, ~0.07 km2)

feats = json.load(open(SRC, encoding='utf-8'))['features']
geoms = {KEYS[f['properties']['dc_eng']]: shape(f['geometry']) for f in feats}
assert len(geoms) == 18, sorted(geoms)
minx = min(g.bounds[0] for g in geoms.values()); maxx = max(g.bounds[2] for g in geoms.values())
miny = min(g.bounds[1] for g in geoms.values()); maxy = max(g.bounds[3] for g in geoms.values())
kx = math.cos(math.radians((miny + maxy) / 2))
scale = W / ((maxx - minx) * kx)
H = round((maxy - miny) * scale)
pt = lambda x, y: (round((x - minx) * kx * scale, 1), round((maxy - y) * scale, 1))

out = {}
for k, g in geoms.items():
    polys = list(g.geoms) if isinstance(g, MultiPolygon) else [g]
    polys = [p for p in polys if p.area >= MIN_AREA]
    d = []
    for p in polys:
        p = p.simplify(TOL, preserve_topology=True)
        for ring in [p.exterior]:          # interior holes are tiny here; skip them
            c = [pt(x, y) for x, y in ring.coords]
            d.append('M' + 'L'.join(f'{x:g},{y:g}' for x, y in c) + 'Z')
    big = max(polys, key=lambda p: p.area)
    lx, ly = pt(*big.representative_point().coords[0])
    out[k] = {'d': ''.join(d), 'lx': lx, 'ly': ly}

js = ('\n// Generated by tools/build_map.py from the 2021 Population Census district boundaries (C&SD, CSDI portal).\n'
      f'const MAP_W={W},MAP_H={H};\nconst MAP_PATHS=' + json.dumps(out, separators=(',', ':')) + ';\n')
# embed in the game so it stays a single self-contained file
html = open(OUT, encoding='utf-8').read()
a, b = html.index('/*MAP-START*/') + len('/*MAP-START*/'), html.index('/*MAP-END*/')
open(OUT, 'w', encoding='utf-8').write(html[:a] + js + html[b:])
print(OUT, 'map size', sum(len(v['d']) for v in out.values()), 'chars; viewBox', W, H)
